// Generates random (but seeded, so reproducible) travel test data.
// Usage: node scripts/generate-data.mjs [seed]
import { writeFileSync, mkdirSync } from 'node:fs';

let seed = Number(process.argv[2] ?? 42);
function rand() {
  // mulberry32
  seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const int = (min, max) => Math.floor(rand() * (max - min + 1)) + min;

const first = ['Aarav', 'Mei', 'Lucas', 'Fatima', 'Noah', 'Priya', 'Sofia', 'Kenji', 'Amara', 'Diego', 'Olivia', 'Ravi', 'Zanele', 'Elif', 'Mateo', 'Hana'];
const last = ['Sharma', 'Chen', 'Silva', 'Okafor', 'Müller', 'Nguyen', 'García', 'Tanaka', 'Haddad', 'Kowalski', "O'Brien", 'Rossi', 'Johansson', 'Patel'];
const airports = ['JFK', 'LHR', 'LIS', 'HND', 'CDG', 'DXB', 'SIN', 'SYD', 'GRU', 'BOM', 'YYZ', 'FRA'];
const tiers = ['Blue', 'Silver', 'Gold', 'Platinum'];
const statuses = ['Confirmed', 'Pending', 'Cancelled'];

const users = Array.from({ length: 25 }, (_, i) => {
  const name = `${pick(first)} ${pick(last)}`;
  return {
    id: `U${1000 + i}`,
    name,
    email: `${name.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z]+/g, '.')}@example.com`,
    phone: `+1-555-${String(int(100, 999))}-${String(int(1000, 9999))}`,
    tier: pick(tiers),
    points: int(0, 250000),
  };
});

const bookings = Array.from({ length: 20 }, (_, i) => {
  const from = pick(airports);
  let to = pick(airports);
  while (to === from) to = pick(airports);
  const d = new Date(2026, int(0, 11), int(1, 28));
  return {
    id: `BK-${String(int(100000, 999999))}`,
    passenger: pick(users).name,
    from,
    to,
    date: d.toISOString().slice(0, 10),
    status: pick(statuses),
    fare: int(89, 2400),
  };
});

const data = { users, bookings };
mkdirSync('data', { recursive: true });
writeFileSync('data/test-data.json', JSON.stringify(data, null, 2) + '\n');
writeFileSync('data/test-data.js', `// Generated by scripts/generate-data.mjs — do not edit by hand.\nwindow.TEST_DATA = ${JSON.stringify(data, null, 2)};\n`);
console.log(`Wrote ${users.length} users and ${bookings.length} bookings to data/`);
